#!/usr/bin/env python3
"""Create a resumable game workspace without overwriting existing work.

The workspace keeps the established ``projects/<slug>/`` layout and scaffolds
symlinks to the reusable toolkit so the existing skill commands work unchanged.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import pipeline_state as state  # noqa: E402

TOOLKIT_ROOT = Path(__file__).resolve().parents[1]


def write_if_absent(path: Path, content: str, created: list[str],
                    skipped: list[str]) -> None:
    if path.exists():
        skipped.append(str(path))
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    created.append(str(path))


def scaffold_symlink(workspace: Path, name: str, target: Path,
                     created: list[str], skipped: list[str],
                     warnings: list[str]) -> None:
    link = workspace / name
    if os.path.lexists(link):
        skipped.append(str(link))
        return
    try:
        link.symlink_to(target, target_is_directory=target.is_dir())
        created.append(f"{link} -> {target}")
    except OSError as exc:
        warnings.append(f"could not create {link} -> {target}: {exc}")


def game_spec_from_template(title: str, slug: str) -> str | None:
    template = TOOLKIT_ROOT / "templates" / "GAME_SPEC.md"
    if not template.is_file():
        return None
    text = template.read_text(encoding="utf-8")
    text = text.replace("# <Game Title>", f"# {title}")
    text = text.replace("`<game_slug>`", f"`{slug}`")
    return text


