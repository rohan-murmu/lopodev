def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", default=".", help="workspace root")
    parser.add_argument("--slug", required=True)
    parser.add_argument("--title", required=True)
    parser.add_argument("--godot-version", default="4.6.1")
    parser.add_argument("--blender-version", default="5.2.2")
    parser.add_argument("--no-scaffold", action="store_true",
                        help="do not symlink tools/templates/AGENTS.md")
    args = parser.parse_args()

    workspace = Path(args.workspace).expanduser().resolve()
    project = workspace / "projects" / args.slug
    state_file = project / state.STATE_FILENAME
    project_file = project / "project.json"

    if not state.SLUG_RE.match(args.slug):
        print("ERROR: slug must be lowercase snake_case starting with a letter",
              file=sys.stderr)
        return 2
    if not args.title.strip():
        print("ERROR: title must be non-empty", file=sys.stderr)
        return 2
    if state_file.exists() or project_file.exists():
        print(f"ERROR: project already exists, refusing to overwrite: {project}",
              file=sys.stderr)
        return 2

    created: list[str] = []
    skipped: list[str] = []
    warnings: list[str] = []

    for relative in (
        "blender",
        "godot/assets/models",
        "godot/scenes",
        "godot/scripts",
        "artifacts/logs",
        "artifacts/screenshots",
        "docs",
        "build",
    ):
        directory = project / relative
        if directory.exists():
            skipped.append(str(directory))
        else:
            directory.mkdir(parents=True, exist_ok=True)
            created.append(str(directory))

    write_if_absent(project_file,
                    json.dumps(project_json(args.slug, args.title.strip(),
                                            args.godot_version,
                                            args.blender_version),
                               indent=2) + "\n",
                    created, skipped)

    spec = game_spec_from_template(args.title.strip(), args.slug)
    if spec is None:
        warnings.append("templates/GAME_SPEC.md missing; GAME_SPEC.md not created")
    else:
        write_if_absent(project / "GAME_SPEC.md", spec, created, skipped)

    write_if_absent(
        project / "ASSET_LICENSES.md",
        "# Asset Licenses\n\n"
        "No third-party assets are recorded yet. Procedurally generated assets "
        "are repository-owned. Any imported asset must be CC0/CC-BY-compatible "
        "or explicitly permitted, with source and attribution recorded here.\n",
        created,
        skipped,
    )
    write_if_absent(project / "godot" / "project.godot",
                    godot_project(args.title.strip()), created, skipped)
    write_if_absent(project / "godot" / "export_presets.cfg",
                    export_presets(args.slug), created, skipped)
    write_if_absent(project / "godot" / "scenes" / "Main.tscn",
                    main_scene_scaffold(), created, skipped)

    state_data = state.new_state(args.slug, args.title.strip(), str(workspace),
                                 str(project))
    state.save_state(str(project), state_data)
    created.append(str(state_file))
    events = project / "artifacts" / "events.jsonl"
    if not events.exists():
        events.write_text(json.dumps({
            "ts_utc": state.utc_now(),
            "event": "project_init",
            "status": "created",
            "command": "tools/bootstrap_project.py",
            "message": f"Bootstrapped {args.slug}; Gate A not yet proposed.",
        }, sort_keys=True) + "\n", encoding="utf-8")
        created.append(str(events))

    if not args.no_scaffold:
        scaffold_symlink(workspace, "tools", TOOLKIT_ROOT / "tools",
                         created, skipped, warnings)
        scaffold_symlink(workspace, "templates", TOOLKIT_ROOT / "templates",
                         created, skipped, warnings)
        scaffold_symlink(workspace, "AGENTS.md", TOOLKIT_ROOT / "AGENTS.md",
                         created, skipped, warnings)
        scaffold_symlink(workspace, ".gitignore", TOOLKIT_ROOT / ".gitignore",
                         created, skipped, warnings)
        scaffold_symlink(workspace, ".opencode", TOOLKIT_ROOT / ".opencode",
                         created, skipped, warnings)
        write_if_absent(workspace / "opencode.json", opencode_config(),
                        created, skipped)

    summary = {
        "workspace": str(workspace),
        "project": str(project),
        "state": str(state_file),
        "created": created,
        "skipped": skipped,
        "warnings": warnings,
        "next_step": (
            "Run game-planner, write GAME_SPEC.md and project.json, validate with "
            "tools/validate_spec.py, sync tasks with pipeline_state.py sync-spec, "
            "then propose gate A."
        ),
    }
    print(json.dumps(summary, indent=2))
    print(f"PROJECT_BOOTSTRAPPED={project}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
